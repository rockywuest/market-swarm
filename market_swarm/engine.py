"""Simulation engine for Market Swarm.

Orchestrates agent evaluation of products using LLM-powered personas.
Industry-specific logic lives in industry_packs/ — this module is pack-agnostic.

Provides both sync (CLI) and async (API) execution paths:
- run_simulation()       — sequential, for CLI
- run_simulation_async() — parallel with semaphore, for API
"""

