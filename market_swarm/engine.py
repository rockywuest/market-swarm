async def evaluate_with_agent_async(
    persona,
    product: Product,
    focus_areas: list[str],
    model: str = "claude-sonnet-4-5",
    *,
    semaphore: asyncio.Semaphore | None = None,
) -> AgentResponse:
    """Run a single agent evaluation (async — for API use).

    Includes retry with exponential backoff on transient errors (429, 5xx).
    """
    if mock_enabled():
        return _build_agent_response(persona, _mock_evaluation(persona, product))

    backend, client = _get_async_client()
    evaluation_prompt = build_evaluation_prompt(product, focus_areas)
    resolved_model, token_limit = _resolve_model(backend, model)

    async def _call_llm() -> str:
        if backend == "anthropic":
            response = await client.messages.create(
                model=model,
                max_tokens=1024,
                system=persona.to_system_message(),
                messages=[{"role": "user", "content": evaluation_prompt}],
            )
            return response.content[0].text
        else:
            response = await client.chat.completions.create(
                model=resolved_model,
                max_tokens=token_limit,
                messages=[
                    {"role": "system", "content": persona.to_system_message()},
                    {"role": "user", "content": evaluation_prompt},
                ],
            )
            return response.choices[0].message.content

    # Retry loop with backoff
    last_error = None
    for attempt in range(MAX_RETRIES):
        try:
            if semaphore:
                async with semaphore:
                    text = await _call_llm()
            else:
                text = await _call_llm()

            data = _parse_llm_response(text)
            return _build_agent_response(persona, data)

        except (anthropic.RateLimitError, openai.RateLimitError) as e:
            last_error = e
            delay = RETRY_BASE_DELAY * (2**attempt)
            logger.warning(
                "Rate limited on %s (attempt %d/%d), retrying in %.1fs",
                persona.name,
                attempt + 1,
                MAX_RETRIES,
                delay,
            )
            await asyncio.sleep(delay)

        except (anthropic.APIStatusError, openai.APIStatusError) as e:
            status = getattr(e, "status_code", 0)
            if status >= 500:
                last_error = e
                delay = RETRY_BASE_DELAY * (2**attempt)
                logger.warning(
                    "Server error %d on %s (attempt %d/%d), retrying in %.1fs",
                    status,
                    persona.name,
                    attempt + 1,
                    MAX_RETRIES,
                    delay,
                )
                await asyncio.sleep(delay)
            else:
                raise  # 4xx (except 429) = don't retry

    raise RuntimeError(f"Failed after {MAX_RETRIES} retries for {persona.name}: {last_error}")


async def run_simulation_async(
    product_path: str,
    model: str = "claude-sonnet-4-5",
    pack_override: str | None = None,
    max_concurrent: int = DEFAULT_MAX_CONCURRENT,
    on_progress: Optional[callable] = None,
) -> SimulationResult:
    """Run a full market simulation with parallel LLM calls.

    Args:
        product_path: Path to product YAML file.
        model: LLM model name.
        pack_override: Force a specific industry pack.
        max_concurrent: Max parallel LLM calls (default 5).
        on_progress: Optional callback(completed: int, total: int) for progress tracking.
    """
    product, config = load_product(product_path)

    product_type = pack_override or product.product_type
    pack = get_pack(product_type)
    personas_to_run = pack.personas
    total = len(personas_to_run)
    semaphore = asyncio.Semaphore(max_concurrent)

    completed_count = 0

    async def _eval_one(persona) -> AgentResponse | None:
        nonlocal completed_count
        try:
            result = await evaluate_with_agent_async(
                persona=persona,
                product=product,
                focus_areas=config.focus_areas,
                model=model,
                semaphore=semaphore,
            )
            completed_count += 1
            if on_progress:
                on_progress(completed_count, total)
            return result
        except Exception as e:
            logger.error("Agent %s failed: %s", persona.name, e)
            completed_count += 1
            if on_progress:
                on_progress(completed_count, total)
            return None

    results = await asyncio.gather(*[_eval_one(p) for p in personas_to_run])
    responses = [r for r in results if r is not None]

    return _aggregate_results(product, responses)


def print_results(result: SimulationResult) -> None:
    """Print simulation results in a formatted table."""
    pack = get_pack(result.product.product_type)
    panel_info = pack.prompt_builder.build_panel_info(result.product)
    rate_label = panel_info.get("rate_label", "Listing Rate")

    console.print()
    console.print(
        Panel(
            f"Product: [bold]{result.product.name}[/bold] ({result.product.brand})\n"
            f"Agents: {len(result.responses)} | Avg Score: {result.avg_score:.1f}/10 | "
            f"{rate_label}: {result.listing_rate:.0%}",
            title="Market Swarm Results",
            border_style="green"
            if result.avg_score >= 7
            else "yellow"
            if result.avg_score >= 5
            else "red",
        )
    )

    # Channel breakdown
    table = Table(title="Agent Scores")
    table.add_column("Agent", style="cyan")
    table.add_column("Score", justify="right")
    table.add_column("Key Feedback")

    for r in result.responses:
        channel = r.retailer or r.agent_type
        emoji = "\u2705" if r.would_list else "\u274c"
        score_style = "green" if r.score >= 7 else "yellow" if r.score >= 5 else "red"
        table.add_row(
            f"{emoji} {r.agent_name} ({channel})",
            f"[{score_style}]{r.score:.1f}[/{score_style}]",
            r.key_feedback,
        )

    console.print(table)

    # Top objections
    if result.top_objections:
        console.print("\n[bold red]Top Objections:[/bold red]")
        for i, obj in enumerate(result.top_objections[:5], 1):
            console.print(f"  {i}. {obj}")

    # Top suggestions
    if result.top_suggestions:
        console.print("\n[bold green]Top Suggestions:[/bold green]")
        for i, sug in enumerate(result.top_suggestions[:5], 1):
            console.print(f"  {i}. {sug}")

    # EU AI Act Art. 50 — Transparency disclaimer
    console.print(f"\n[dim]Note: {DISCLAIMER}[/dim]")
